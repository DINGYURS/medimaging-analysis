-- Approved and applied on 2026-11-13. One-time migration; not run on app startup.
-- MySQL 8.0; existing parent IDs checked with SHOW CREATE TABLE (signed BIGINT).
CREATE TABLE radiomics_calculation_runs (
  id CHAR(36) NOT NULL PRIMARY KEY,
  analysis_task_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  created_by_id BIGINT NOT NULL,
  active_task_id BIGINT NULL,
  status VARCHAR(24) NOT NULL,
  config JSON NOT NULL,
  catalog_version VARCHAR(80) NOT NULL,
  engine_version VARCHAR(80) NOT NULL,
  configuration_hash CHAR(64) NOT NULL,
  input_hash CHAR(64) NOT NULL,
  input_snapshot JSON NOT NULL,
  selected_count SMALLINT UNSIGNED NOT NULL,
  total_lesions INT UNSIGNED NOT NULL,
  completed_lesions INT UNSIGNED NOT NULL DEFAULT 0,
  error_summary JSON NULL,
  artifact_manifest JSON NULL,
  worker_token CHAR(36) NULL,
  heartbeat_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  CONSTRAINT fk_rc_runs_task FOREIGN KEY (analysis_task_id) REFERENCES analysis_tasks(id) ON DELETE CASCADE,
  CONSTRAINT fk_rc_runs_doctor FOREIGN KEY (doctor_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_rc_runs_creator FOREIGN KEY (created_by_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT ck_rc_runs_selected CHECK (selected_count BETWEEN 1 AND 198),
  CONSTRAINT ck_rc_runs_status CHECK (status IN ('pending','running','succeeded','partial','failed','interrupted')),
  CONSTRAINT ck_rc_runs_active CHECK (active_task_id IS NULL OR active_task_id = analysis_task_id),
  UNIQUE KEY uq_rc_runs_active (active_task_id),
  KEY ix_rc_runs_task_created (analysis_task_id,created_at),
  KEY ix_rc_runs_doctor_created (doctor_id,created_at),
  KEY ix_rc_runs_status_heartbeat (status,heartbeat_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE radiomics_calculation_results (
  id CHAR(36) NOT NULL PRIMARY KEY,
  run_id CHAR(36) NOT NULL,
  lesion_id BIGINT NOT NULL,
  lesion_index INT NOT NULL,
  status VARCHAR(24) NOT NULL,
  selected_count SMALLINT UNSIGNED NOT NULL,
  computed_count SMALLINT UNSIGNED NOT NULL,
  unavailable_count SMALLINT UNSIGNED NOT NULL,
  features JSON NOT NULL,
  unavailable JSON NOT NULL,
  provenance JSON NOT NULL,
  error_message TEXT NULL,
  created_at DATETIME(6) NOT NULL,
  CONSTRAINT fk_rc_results_run FOREIGN KEY (run_id) REFERENCES radiomics_calculation_runs(id) ON DELETE CASCADE,
  CONSTRAINT fk_rc_results_lesion FOREIGN KEY (lesion_id) REFERENCES lesions(id) ON DELETE CASCADE,
  CONSTRAINT ck_rc_results_status CHECK (status IN ('computed','partial','failed')),
  CONSTRAINT ck_rc_results_counts CHECK (selected_count BETWEEN 1 AND 198 AND computed_count + unavailable_count = selected_count),
  UNIQUE KEY uq_rc_results_run_lesion (run_id,lesion_id),
  KEY ix_rc_results_lesion (lesion_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
